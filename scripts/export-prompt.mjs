#!/usr/bin/env node
/**
 * Render ember_prompt.md from lib/ember.js so the readable mirror cannot drift
 * from the code. Usage: node scripts/export-prompt.mjs
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  MODEL_LABEL,
  OUTPUT_SCHEMA,
  PER_LISTING_USD,
  STUB_LISTING,
  STUB_USAGE,
  SYSTEM_PROMPT,
  buildUserPrompt
} from '../lib/ember.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'ember_prompt.md');

const bullets = OUTPUT_SCHEMA.schema.properties.bullets;
const tags = OUTPUT_SCHEMA.schema.properties.seo_tags;

const userTemplate = buildUserPrompt({
  productName: '{product name}',
  specs: '{supplier specs text}',
  hasImage: true
});

const doc = `# Muse Ember — listing prompt and output contract

Generated from [\`lib/ember.js\`](lib/ember.js) by \`node scripts/export-prompt.mjs\`. Do not edit this file by
hand — change the code and re-run the script. If the two ever disagree, the code wins.

Model: **Muse Ember via the Meta Model API** — \`${MODEL_LABEL}\` (\`EMBER_MODEL\`), with prices confirmed
against https://dev.meta.ai/models/muse-ember on 24 Nov 2026.

## System prompt

> ${SYSTEM_PROMPT}

## User message

\`\`\`
${userTemplate}
\`\`\`

Without a photo, the second line reads \`No product photo is attached.\` instead.

Implementation: the system prompt goes in the \`system\` message; the block above is a single \`user\` message,
with the photo attached as an \`image_url\` part when there is one.

## Output schema

\`\`\`json
${JSON.stringify(OUTPUT_SCHEMA, null, 2)}
\`\`\`

## Contract checks after parsing

\`normaliseListing()\` trims and clamps — it never adds content:

- title collapses whitespace; over 140 characters gets cut on a word boundary
- description keeps its blank-line paragraph breaks
- bullets: ${bullets.minItems}–${bullets.maxItems} kept, empties dropped
- seo_tags: lowercased, de-duplicated, max ${tags.maxItems}

## Stub sample (no key in \`.env\`)

While \`META_MODEL_API_KEY\` is absent, \`POST /api/generate\` returns this for every product:

\`\`\`json
${JSON.stringify(STUB_LISTING, null, 2)}
\`\`\`

Fixed stub usage: ${STUB_USAGE.tokensIn.toLocaleString('en-US')} tokens in, ${STUB_USAGE.tokensOut.toLocaleString('en-US')} out, $${PER_LISTING_USD.toFixed(4)} — so the cost meter and trace panel exercise the real code path before any credits are spent.

## Swapping the stub for the real call

1. Put the key in \`.env\` as \`META_MODEL_API_KEY=...\`.
2. Confirm \`EMBER_BASE_URL\` / \`EMBER_MODEL\` and the response shape against Meta's Model API docs (the request
   uses the OpenAI-compatible chat-completions shape with \`response_format: json_schema\`).
3. Restart \`npm start\`. \`isStubMode()\` turns false and \`callEmber()\` runs; cost comes from the returned token
   usage at the confirmed $0.10 / million input and $0.50 / million output ($0.004 cached input).
`;

await writeFile(OUT, doc, 'utf8');
console.log(`wrote ${path.relative(ROOT, OUT)} · bullets ${bullets.minItems}-${bullets.maxItems} · tags ${tags.minItems}-${tags.maxItems}`);
